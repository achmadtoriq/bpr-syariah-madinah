    function sliderGallery() {
        return {
            images: [],
            slideGroups: [],
            swiper: null,

            async init() {
                try {
                    const res = await fetch('/api/galeri_all');
                    const data = await res.json();
                    this.images = Array.isArray(data) ? data : [];
                    this.slideGroups = this.chunkArray(this.images, 4);

                    this.$nextTick(() => {
                        this.waitUntilImagesLoaded().then(() => {
                            this.swiper = new Swiper('.swiper', {
                                loop: this.slideGroups.length > 1,
                                autoplay: {
                                    delay: 3500,
                                    disableOnInteraction: false
                                },
                                effect: 'slide',
                                speed: 700,
                            });
                        });
                    });
                } catch (e) {
                    console.error('Gagal memuat galeri:', e);
                }
            },

            chunkArray(arr, size) {
                const chunked = [];
                for (let i = 0; i < arr.length; i += size) {
                    chunked.push(arr.slice(i, i + size));
                }
                return chunked;
            },

            waitUntilImagesLoaded() {
                return new Promise((resolve) => {
                    const images = document.querySelectorAll('.swiper-slide img');
                    if (images.length === 0) return resolve();

                    let loaded = 0;
                    images.forEach(img => {
                        if (img.complete) {
                            loaded++;
                            if (loaded === images.length) resolve();
                        } else {
                            img.addEventListener('load', () => {
                                loaded++;
                                if (loaded === images.length) resolve();
                            });
                            img.addEventListener('error', () => {
                                loaded++;
                                if (loaded === images.length) resolve();
                            });
                        }
                    });
                });
            }
        }
    }
